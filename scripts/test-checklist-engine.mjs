import fs from "node:fs";import vm from "node:vm";
const sandbox={console};sandbox.globalThis=sandbox;vm.createContext(sandbox);
vm.runInContext(fs.readFileSync("src/checklistEngine.js","utf8"),sandbox);
const metadata=JSON.parse(fs.readFileSync("data/products/2026-topps-chrome-premier-league.json","utf8"));
const base=JSON.parse(fs.readFileSync("data/checklists/2026-topps-chrome-premier-league-base.json","utf8"));
const autos=JSON.parse(fs.readFileSync("data/checklists/2026-topps-chrome-premier-league-chrome-autographs.json","utf8"));
const E=sandbox.BreakMetricChecklist;
const b=E.normalize(base,metadata),a=E.normalize(autos,metadata);
if(!b.valid) throw new Error("base checklist invalid: "+b.errors.join("; "));
if(!a.valid) throw new Error("autograph checklist invalid: "+a.errors.join("; "));
if(new Set(b.cards.map(x=>x.card_id)).size!==b.cards.length) throw new Error("base IDs collide");
if(new Set(a.cards.map(x=>x.card_id)).size!==a.cards.length) throw new Error("auto IDs collide");
if(b.cards.some(x=>a.cards.some(y=>y.card_id===x.card_id))) throw new Error("card-family collision");
const wrong={...base,product_id:"wrong-product"};
if(E.validate(wrong,metadata).valid) throw new Error("wrong product accepted");
const duplicate={...base,cards:[base.cards[0],base.cards[0]]};
if(E.validate(duplicate,metadata).valid) throw new Error("duplicate accepted");
const badTeam={...base,cards:[{...base.cards[0],team:"Not a canonical team"}]};
if(E.validate(badTeam,metadata).valid) throw new Error("unknown team accepted");
console.log(JSON.stringify({result:"pass",base_cards:b.cards.length,autograph_cards:a.cards.length,checks:["stable card ids","family collision protection","product mismatch rejection","duplicate rejection","team reference integrity"]},null,2));
